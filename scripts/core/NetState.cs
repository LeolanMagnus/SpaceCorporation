using Godot;

namespace SpaceCorporation;

/// <summary>
/// Узел-хранилище «сетевого» состояния тела (решение В6: реплицируем состояние,
/// а не трансформ `RigidBody3D`). Висит дочерним узлом у `Ship` (позже у других
/// симулируемых объектов) и настраивается `MultiplayerSynchronizer` с
/// `RootPath = ".."`; в `SceneReplicationConfig` свойства адресуются от RootPath,
/// то как `NetState/NetPosition` (§3.3).
///
/// Свойства обязаны быть `[Export] public ... { get; set; }`: Godot реплицирует и
/// считает спавн-снимком только свойства, видимые его отражению. C#-поле без
/// атрибута репликацией не покрывается, и снимок молча не приходит (§3.11 п.2).
///
/// Здесь НЕТ `GlobalPosition`/`GlobalRotation` самого тела: писать репликой в
/// трансформ `RigidBody3D` — конфликт с локальной физикой каждый кадр (§1.11).
/// Картинку интерполирует узел `ShipHull`, тело двигает только авторитет.
/// </summary>
public partial class NetState : Node
{
    [Export] public Vector3 NetPosition { get; set; }
    [Export] public Quaternion NetRotation { get; set; } = Quaternion.Identity;
    [Export] public Vector3 NetLinearVelocity { get; set; }
    [Export] public Vector3 NetAngularVelocity { get; set; }

    /// <summary>Физический шаг (`Engine.GetPhysicsFrames()`), на котором авторитет
    /// сделал снимок. По нему принимающий отбрасывает устаревшие репорты.</summary>
    [Export] public int SimTick { get; set; }

    /// <summary>Тик кадра ввода, который сервер применил к этому снимку (шаг 2.3,
    /// §1.5 плана). Реконсиляция на пилоте (шаг 2.4) откатывает предсказание к
    /// эталону и переигрывает только кадры с `Tick > AppliedTick`. Без этого поля
    /// пилот не знает, какой именно ввод уже учтён эталоном, и переигрывает лишнее.</summary>
    [Export] public int AppliedTick { get; set; }

    /// <summary>Маска того же применённого кадра (для панели отладки и assert'ов:
    /// видно, каким именно вводом сервер получил эту позицию).</summary>
    [Export] public uint AppliedMask { get; set; }

    /// <summary>Сетевой адрес владельца (один монотонный счётчик на все спавнящиеся
    /// объекты мира, §3.4 п.2). Выдаёт сервер ДО `AddChild` (§4 В4 п.3);
    /// 0 = не назначен — `Ship._Ready()` обязан сообщить об этом в отладку.</summary>
    [Export] public int ShipNetId { get; set; }

    // ─────────────────── Этап 5 (шаг 5.3): стыковка ───────────────────
    // Фаза стыковки этого корабля (byte enum DockState) и адрес станции, к
    // которой она идёт. Нужны пиру-не-пилоту для отрисовки (огни/док-бикон) и
    // пилоту для гейта предсказания (5.9: на dock-фазе кадры не шлёт).
    // Писает только сервер (NetState-поля корабля — «правда сервера», как SimTick).

    /// <summary>Фаза сделки (<c>(DockState)DockStateValue</c>), 0 = None.</summary>
    [Export] public byte DockStateValue { get; set; }

    /// <summary>StationNetId цели стыковки (0 — нет сделки).</summary>
    [Export] public int DockStationNetId { get; set; }

    // ─────────────────── Этап 6: поддержка пилотирования ───────────────────
    // Флаг «жидкого космоса» этого корабля (byte bool): 1 = пилот-ассист ВКЛ
    // (без тяги скорость гасится тем же ускорением, что набирается). Пишет его
    // только сервер по RPC пилота (RpcTogglePilotAssist), реплика — OnChange
    // (событие редкое, поток не создаёт, как у DockStateValue). Нужен:
    //  • пилоту-клиенту — сверять ЛОКАЛЬНОЕ предсказание (Loadout.PilotAssist,
    //    инвертируется сразу при нажатии T) с истиной сервера: расхождение =
    //    жёсткий откат предсказания и переигровка буфера с новым флагом;
    //  • всем пират — что вообще показывает дебаг-строка `assist = ON|OFF`.

    /// <summary>Пилот-ассист включён (<c>Loadout.PilotAssist</c>, 1 = ВКЛ).</summary>
    [Export] public byte PilotAssist { get; set; } = 1;

    // ─────────────────── Тип корабля (три пресета полётной модели) ──────────
    // Тип корабля (byte enum <c>ShipType</c>, 0 = Courier): по нему Ship при
    // спавне берёт из ShipStatCatalog набор характеристик полётной модели,
    // массу и вид корпуса. Пишет тип ТОЛЬКО сервер (по RPC локального пилота
    // из дебаг-панели), транспорт — как у PilotAssist: OnChange-дельта +
    // спавн-снимок для поздно зашедшего пира. Смена редкая (дебаг-кнопка),
    // на трафик не влияет.

    /// <summary>Тип корабля (<c>(ShipType)ShipTypeValue</c>), 0 = Courier.</summary>
    [Export] public byte ShipTypeValue { get; set; } = (byte)ShipType.Courier;

    // ─────────────────── Этап H4 (hud-plan.md §1): фракция ───────────────────
    // Фракция корабля (byte enum <c>Faction</c>, 0 = Neutral). Пишет авторитет
    // при спавне (в сети — сервер ДО AddChild, в offline — спавнер); транспорт
    // как у ShipTypeValue: спавн-снимок + ON_CHANGE (значение статичное, трафик
    // не создаёт). Нужен HUD: цвет цели/своего корабля по фракции.

    /// <summary>Фракция (<c>(Faction)FactionValue</c>), 0 = Neutral.</summary>
    [Export] public byte FactionValue { get; set; } = (byte)Faction.Neutral;

    // ── frame-plan шаг 6: захват (пузырь кадра-системы) ──────────────────────
    // Id корабля-родителя, чей кадр интегрирует это тело (0 = не захвачен).
    // Писатель — только авторитет (переход считает CaptureRules на сервере или
    // в offline). Транспорт — тот же, что у DockStateValue/PilotAssist:
    // спавн-снимок (поздно зашедший пир обязан увидеть факт захвата сразу) +
    // OnChange-дельта на редких переходах (вход/выход из пузыря — единицы
    // событий, трафик поля боя не трогают). В батч SnapshotBroadcaster поле НЕ
    // идёт: запись батча фиксированного формата, редкое событие дешевле возить
    // дельтой синхронизатора (тот же аргумент, что у dock-полей, шаг 5.3).
    [Export] public int CaptureParentNetId { get; set; }

    // Тик авторитетного шага ПОСЛЕДНЕГО перехода захвата (вход/выход). Клиент-
    // пилот при сдвиге этого тика сбрасывает предсказание: сервер интегрирует
    // шаги уже в новом режиме (в кадре / вне кадра), а клиент про переход
    // узнаёт с лагом — разница «перенесено/не перенесено» на тиках между
    // переходом и его репликой дала бы метры ложной ошибки предсказания
    // (§7.1 frame-plan, гейт по образцу dock-фазы В20).
    [Export] public int CaptureTick { get; set; }

    /// <summary>Адрес выдаёт НЕ этот узел: в сети номер назначает сервер до
    /// `AddChild` (§4 В4 п.3), иначе два пира выдали бы разные номера одному
    /// кораблю. В offline (`Role == Offline`, один процесс) адрес выдаёт
    /// `NetworkManager` — счётчик тот же, поэтому offline и сеть не разъезжаются
    /// (§1.8), а панель показывает `Ship#1` и в одиночном режиме (§3.1 п.6).
    /// `_EnterTree`, а не `_Ready`: обход при входе идёт сверху вниз, поэтому
    /// `AttachPoint` (дочерний узел) увидит уже назначенный `OwnerNetId`.</summary>
    public override void _EnterTree()
    {
        NetworkManager.Instance?.AssignNetIdIfUnset(this);
    }
}
